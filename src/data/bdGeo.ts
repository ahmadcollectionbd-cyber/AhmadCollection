/**
 * Helper: given a district name, find which division it belongs to and
 * whether it matches the shop's base city (for auto inside/outside detection).
 */
export function findDivisionForDistrict(districtName: string): Division | undefined {
  const lower = districtName.trim().toLowerCase();
  return BD_DIVISIONS.find((div) =>
    div.districts.some((d) => d.name.toLowerCase() === lower || d.nameBn === districtName.trim()),
  );
}
